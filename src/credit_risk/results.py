def test_summary(root: Path) -> dict[str, int] | None:
    path = root / "results" / "pytest.xml"
    if not path.exists():
        return None
    suite = ET.parse(path).getroot()
    suite = suite[0] if suite.tag == "testsuites" else suite
    total, failures, errors, skipped = (
        int(suite.get(k, 0)) for k in ("tests", "failures", "errors", "skipped")
    )
    return {
        "total": total,
        "passed": total - failures - errors - skipped,
        "failed": failures + errors,
        "skipped": skipped,
    }


def collect(settings) -> dict[str, Any]:
    f = load_facts(settings)
    root, results = settings.root, settings.path("results")
    gold = settings.path("gold")
    r_table = pd.read_csv(gold / "reconciliation_r_python.csv")
    return {
        **f,
        "excel": read_json(results / "excel_verification.json"),
        "tableau": read_json(results / "tableau_extracts.json"),
        "benchmarks": read_json(results / "benchmarks.json"),
        "run": read_json(results / "pipeline_run.json"),
        "r": r_table,
        "tests": test_summary(root),
        "layer": pd.read_csv(gold / "dq_layer_checks.csv"),
        "metrics": pd.read_csv(gold / "model_metrics.csv"),
    }


